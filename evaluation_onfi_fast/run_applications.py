#!/usr/bin/env python3
"""FAST24 SQLite/Filebench protocols, ONFI-only A/B, on stock Linux.

Creates and formats ONLY a freshly discovered, verified NVMeVirt namespace.
The external ext4 journal lives on a private tmpfs-backed loop device.
"""
import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import signal
import subprocess
import sys
import tempfile
import time

from runner import ROOT, run, capture, namespaces, verify_device, counters, validate_log
from summarize import stats, delta

FILEBENCH_COMMIT = "1263cb180c48a63253345a12e2b842cd9f85fa26"
FILEBENCH = ROOT / "evaluation_onfi_fast/.cache" / ("filebench-" + FILEBENCH_COMMIT) / "filebench"
WORKLOADS = ("sqlite", "fileserver", "fileserver_small")
VM_SETTINGS = {"dirty_background_ratio": "50", "dirty_ratio": "50",
               "dirty_writeback_centisecs": "0", "dirty_expire_centisecs": "60000"}


def save(path, obj):
    path.write_text(json.dumps(obj, indent=2) + "\n")


def filebench_profile(mount, mode, append_kib, seconds, files, append_bytes):
    # Parameters and flowops follow fast24_ae@89ba3a9; locally generated WML.
    # 1.5-alpha3's reuse alone truncates files back to the declared size;
    # trusttree preserves the appended data. SHA256 checks enforce this.
    attr = "prealloc,paralloc" if mode == "append" else "prealloc,readonly,reuse,trusttree"
    operations = ("flowop openfile name=openfile1,filesetname=bigfileset,fd=1\n"
                  f"    flowop appendfile name=appendfile1,iosize={append_kib}k,fd=1\n"
                  "    flowop closefile name=closefile1,fd=1\n"
                  f"    flowop finishonbytes name=finish,value={append_bytes}" if mode == "append" else
                  "flowop openfile name=openfile1,filesetname=bigfileset,fd=1,directio\n"
                  "    flowop readwholefile name=readfile1,fd=1,iosize=1m,directio\n"
                  "    flowop closefile name=closefile1,fd=1")
    return f'''# FAST24 {mode}; generated by run_applications.py
set $dir={mount}
define fileset name=bigfileset,path=$dir,size=131072,entries={files},dirwidth=20,{attr}
define process name=worker,instances=1
{{
  thread name=workerthread,memsize=10m,instances=10
  {{
    {operations}
  }}
}}
run {seconds}
'''


def parse_filebench(path):
    text = path.read_text()
    if re.search(r"(?i)\b(?:error|failed|failure|no space|aborting|segmentation)\b", text):
        raise RuntimeError(f"Filebench error in {path}")
    matches = re.findall(r"IO Summary:\s+(\d+) ops\s+([\d.]+) ops/s\s+([\d.]+)/([\d.]+) rd/wr\s+([\d.]+)mb/s\s+([\d.]+)ms/op", text)
    if len(matches) != 1:
        raise RuntimeError(f"missing/ambiguous Filebench summary: {path}")
    count, ops, reads, writes, mib_s, lat = matches[0]
    took = re.search(r"Run took (\d+) seconds", text)
    flows = {}
    for line in text.splitlines():
        found = re.match(r"\s*(openfile1|appendfile1|readfile1|closefile1)\s+(\d+)ops\s+([\d.]+)ops/s\s+([\d.]+)mb/s\s+([\d.]+)ms/op", line)
        if found:
            flows[found[1]] = {"ops": int(found[2]), "ops_s": float(found[3]),
                              "MiB_s": float(found[4]), "mean_ms": float(found[5])}
    return {"operations": int(count), "ops_s": float(ops), "reads_s": float(reads),
            "writes_s": float(writes), "MiB_s": float(mib_s), "mean_io_ms": float(lat),
            "run_seconds": int(took[1]) if took else None, "flowops": flows}


def app_process(args, output, mount, timeout, telemetry):
    start = time.monotonic()
    next_sample = 0
    with output.open("w") as log, telemetry.open("w") as samples:
        proc = subprocess.Popen(list(map(str, args)), cwd=ROOT, stdout=log,
                                stderr=subprocess.STDOUT, start_new_session=True)
        try:
            while proc.poll() is None:
                elapsed = time.monotonic() - start
                if elapsed > timeout:
                    raise RuntimeError(f"application timeout: {output}")
                if elapsed >= next_sample:
                    free = shutil.disk_usage(mount).free
                    samples.write(json.dumps({"elapsed_s": elapsed, "free_bytes": free,
                                               "counters": Path("/proc/nvmev/debug").read_text()}) + "\n")
                    samples.flush()
                    next_sample = elapsed + 1
                    if free < 256 * 1024**2:
                        raise RuntimeError("16 GiB namespace almost full; refusing to report a truncated run")
                try:
                    proc.wait(timeout=.05)
                except subprocess.TimeoutExpired:
                    pass
            if proc.returncode:
                raise RuntimeError(f"application exited {proc.returncode}: {output}")
        finally:
            if proc.poll() is None:
                os.killpg(proc.pid, signal.SIGTERM)
                try:
                    proc.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    os.killpg(proc.pid, signal.SIGKILL)
                    proc.wait(timeout=10)
    return time.monotonic() - start


def tree_digest(folder, out):
    rows = []
    for path in sorted(folder.rglob("*")):
        if not path.is_file():
            continue
        h = hashlib.sha256()
        with path.open("rb") as f:
            while chunk := f.read(1024**2):
                h.update(chunk)
        rows.append({"path": str(path.relative_to(folder)), "bytes": path.stat().st_size, "sha256": h.hexdigest()})
    save(out, rows)
    return rows


def drop_caches(seconds, twice=False):
    for _ in range(2 if twice else 1):
        os.sync()
        Path("/proc/sys/vm/drop_caches").write_text("3\n")
        time.sleep(seconds)


class Device:
    def __init__(self, folder, cpus, onfi):
        self.folder, self.cpus, self.onfi = folder, cpus, onfi
        self.loaded = self.mounted = False
        self.loop = self.journal = None
        self.mount = folder / "mount"
        self.mount.mkdir()
        self.log_start = capture(["dmesg"])

    def create(self):
        before = namespaces()
        run(["insmod", ROOT / "nvmev.ko", "memmap_start=8G", "memmap_size=16G",
             "cpus=" + self.cpus, f"onfi_collision={self.onfi}", "fast_placement=0"], self.folder / "insmod.log")
        self.loaded = True
        for _ in range(100):
            found = namespaces() - before
            if len(found) == 1:
                self.name = found.pop()
                self.device = verify_device(self.name)
                break
            if len(found) > 1:
                raise RuntimeError("ambiguous new namespaces")
            time.sleep(.1)
        else:
            raise RuntimeError("no virtual namespace")
        if shutil.disk_usage("/dev/shm").free < 1024**3:
            raise RuntimeError("need at least 1 GiB free tmpfs for external journal")
        fd, name = tempfile.mkstemp(prefix="nvmev-fast24-journal-", dir="/dev/shm")
        self.journal = Path(name)
        os.ftruncate(fd, 512 * 1024**2)
        os.close(fd)
        run(["modprobe", "loop"], self.folder / "loop-module.log")
        self.loop = capture(["losetup", "--find", "--show", str(self.journal)])
        backing = Path("/sys/class/block") / Path(self.loop).name / "loop/backing_file"
        if Path(backing.read_text().strip()).resolve() != self.journal.resolve():
            raise RuntimeError("loop backing identity mismatch")
        save(self.folder / "device.json", {"device": self.device, "model": "NVMeVirt_FAST24",
              "logical_bytes": int(capture(["blockdev", "--getsize64", self.device])),
              "journal_loop": self.loop, "journal_backing": str(self.journal), "mount": str(self.mount)})
        run(["mkfs.ext4", "-F", "-O", "journal_dev", "-b", "4096", self.loop], self.folder / "mkfs-journal.log")
        run(["mkfs.ext4", "-F", "-m", "0", "-b", "4096", "-E", "nodiscard,lazy_itable_init=0",
             "-J", "device=" + self.loop, self.device], self.folder / "mkfs.log")
        run(["mount", "-t", "ext4", "-o", "nodelalloc,noatime", self.device, self.mount], self.folder / "mount.log")
        self.mounted = True
        for key, value in (("reserved_clusters", "0"), ("mb_stream_req", "4200000000")):
            (Path("/sys/fs/ext4") / self.name / key).write_text(value + "\n")
        run(["sync", "-f", self.mount], self.folder / "initial-sync.log")
        counters(self.folder / "ready.stats")

    def close(self):
        if self.mounted:
            run(["umount", self.mount], self.folder / "umount.log", timeout=180)
            self.mounted = False
        if self.loop:
            run(["losetup", "--detach", self.loop], self.folder / "loop-detach.log")
            self.loop = None
        if self.journal:
            self.journal.unlink()
            self.journal = None
        if self.loaded:
            run(["rmmod", "nvmev"], self.folder / "rmmod.log")
            self.loaded = False
        end = capture(["dmesg"])
        log = end[len(self.log_start):] if end.startswith(self.log_start) else end
        (self.folder / "dmesg.log").write_text(log)
        validate_log(self.folder / "dmesg.log")
        if re.search(r"EXT4-fs error|Buffer I/O error|I/O error, dev nvme", log, re.I):
            raise RuntimeError("filesystem/block I/O error in kernel log")


def phase(folder, name, command, dev, timeout):
    counters(folder / f"{name}.before.stats")
    start = time.monotonic()
    wall = app_process(command, folder / f"{name}.log", dev.mount, timeout, folder / f"{name}.telemetry.jsonl")
    run(["sync", "-f", dev.mount], folder / f"{name}.sync.log")
    timing = {"process_wall_seconds": wall, "wall_including_drain_seconds": time.monotonic() - start}
    counters(folder / f"{name}.after.stats")
    save(folder / f"{name}.counters.json", delta(stats(folder / f"{name}.after.stats"), stats(folder / f"{name}.before.stats")))
    return timing


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--plan-only", action="store_true")
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--workloads", nargs="+", choices=WORKLOADS, default=list(WORKLOADS))
    ap.add_argument("--groups", nargs="+", choices=("A", "B"), default=["A", "B"])
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--sql-reads", type=int, default=10)
    ap.add_argument("--append-mib", type=int, default=4096)
    ap.add_argument("--append-timeout", type=int, default=300)
    ap.add_argument("--read-seconds", type=int, default=60)
    ap.add_argument("--cpus", default="7,8,9,10")
    ap.add_argument("--host-cpus", default="0,1,2,3,4,5")
    ap.add_argument("--out", type=Path, default=ROOT / "evaluation_onfi_fast/results" /
                    datetime.datetime.now(datetime.timezone.utc).strftime("apps-%Y%m%dT%H%M%SZ"))
    a = ap.parse_args()
    if min(a.repeats, a.sql_reads, a.append_mib, a.append_timeout, a.read_seconds) < 1:
        ap.error("counts and durations must be positive")
    if a.append_mib > 8192:
        ap.error("append budget must fit the 16 GiB namespace with filesystem headroom")
    if a.smoke:
        a.repeats, a.sql_reads, a.append_mib, a.read_seconds = 1, 1, 32, 2
    records, files, wait = (100, 100, .1) if a.smoke else (10000, 10000, 5)
    plan = [{"repeat": rep, "workload": w, "group": g, "onfi": int(g == "B"), "seed": 20261026 + rep}
            for rep in range(1, a.repeats + 1) for w in a.workloads
            for g in (a.groups if rep % 2 else list(reversed(a.groups)))]
    if a.plan_only:
        print(json.dumps({"suite": "stock_host_applications_onfi_only", "plan": plan,
                          "records": records, "files": files, "sql_reads": a.sql_reads,
                          "append_mib": a.append_mib, "read_seconds": a.read_seconds}, indent=2))
        return
    if os.geteuid() or "memmap=16G$8G" not in Path("/proc/cmdline").read_text().split():
        raise RuntimeError("requires root and verified 16 GiB reservation")
    if Path("/sys/module/nvmev").exists():
        raise RuntimeError("refusing existing nvmev module")
    if set(a.cpus.split(",")) & set(a.host_cpus.split(",")):
        raise RuntimeError("application/emulator CPUs must be separate")
    if not FILEBENCH.is_file() and any(w.startswith("fileserver") for w in a.workloads):
        raise RuntimeError("run bash evaluation_onfi_fast/prepare_filebench.sh first")
    a.out = a.out.resolve()
    # WML paths intentionally stay inside the experiment workspace, without shell syntax.
    if not a.out.is_relative_to(ROOT / "evaluation_onfi_fast/results") or re.search(r"[\s\"'\\$]", str(a.out)):
        raise RuntimeError("output must be a simple path inside evaluation_onfi_fast/results")
    a.out.mkdir(parents=True, exist_ok=False)
    manifest = {"suite": "stock_host_applications_onfi_only", "status": "running", "smoke": a.smoke,
                "git_head": capture(["git", "rev-parse", "HEAD"]), "git_status": capture(["git", "status", "--porcelain"]),
                "kernel": capture(["uname", "-r"]), "physical_bytes": 16 * 1024**3, "fast_placement": False,
                "cpus": a.cpus, "host_cpus": a.host_cpus, "filebench_commit": FILEBENCH_COMMIT,
                "filebench_sha256": hashlib.sha256(FILEBENCH.read_bytes()).hexdigest() if FILEBENCH.exists() else None,
                "records": records, "files": files, "sql_reads": a.sql_reads, "cache_wait_seconds": wait,
                "append_mib": a.append_mib, "append_timeout": a.append_timeout,
                "read_seconds": a.read_seconds, "plan": plan,
                "ext4": "4KiB, nodelalloc,noatime, external 512MiB tmpfs loop journal, no lazy itable init",
                "vm_settings": VM_SETTINGS,
                "notes": ["FAST placement disabled in both groups; stock host supplies no file hints",
                          "Paper append duration 60s; author artifact uses 30s",
                          "16 GiB capacity adaptation: fixed append byte budget, not timed unlimited append",
                          "finishonbytes checks a shared counter; a few concurrent operations may overshoot",
                          "Filebench appendfile uses lseek+write, not atomic O_APPEND; actual file growth is recorded separately",
                          "Read uses trusttree to prevent Filebench preallocation from truncating appended files",
                          "Filebench counters cover creation+append+drain; throughput is its timed append phase"]}
    srcs = ["run_applications.py", "sqlite_workload.c"]
    manifest["source_sha256"] = {p: hashlib.sha256((ROOT / "evaluation_onfi_fast" / p).read_bytes()).hexdigest() for p in srcs}
    save(a.out / "manifest.json", manifest)
    old = {}
    try:
        run(["make", "NVMEV_PROFILE=fast24", "-j4"], a.out / "build.log")
        helper = a.out / "sqlite_workload"
        run(["cc", "-O2", "-Wall", "-Wextra", "-Werror", ROOT / "evaluation_onfi_fast/sqlite_workload.c",
             "-lsqlite3", "-o", helper], a.out / "sqlite-build.log")
        for key in list(VM_SETTINGS) + ["dirty_bytes", "dirty_background_bytes"]:
            old[key] = (Path("/proc/sys/vm") / key).read_text().strip()
        save(a.out / "vm.original.json", old)
        for key, value in VM_SETTINGS.items():
            (Path("/proc/sys/vm") / key).write_text(value + "\n")
        for item in plan:
            folder = a.out / f"r{item['repeat']}" / item["group"] / item["workload"]
            folder.mkdir(parents=True)
            print(f"START {item['group']} {item['workload']} r{item['repeat']}", flush=True)
            dev = Device(folder, a.cpus, item["onfi"])
            try:
                dev.create()
                pin = ["taskset", "-c", a.host_cpus]
                if item["workload"] == "sqlite":
                    common = [dev.mount, records, item["seed"], 102400, 1]
                    timing = phase(folder, "build", pin + [helper, "build"] + common, dev, 900)
                    build = json.loads((folder / "build.log").read_text())
                    save(folder / "build.json", build | timing)
                    run(["filefrag", "-e", dev.mount / "testdb.db"], folder / "filefrag.log")
                    for i in range(1, a.sql_reads + 1):
                        print(f"  SELECT {i}/{a.sql_reads}", flush=True)
                        drop_caches(wait, twice=True)
                        phase(folder, f"read{i}", pin + [helper, "read"] + common, dev, 180)
                        result = json.loads((folder / f"read{i}.log").read_text())
                        save(folder / f"read{i}.json", result)
                    run(pin + [helper, "verify"] + common, folder / "verification.json")
                    if not json.loads((folder / "verification.json").read_text())["verified"]:
                        raise RuntimeError("SQLite verification failed")
                    save(folder / "dataset.json", {"records": records, "database_bytes": (dev.mount / "testdb.db").stat().st_size,
                                                   "dummy_bytes": (dev.mount / "dummy.data").stat().st_size})
                else:
                    size = 16 if item["workload"] == "fileserver_small" else 32
                    for mode, seconds in (("append", a.append_timeout), ("read", a.read_seconds)):
                        profile = folder / f"{mode}.f"
                        profile.write_text(filebench_profile(dev.mount, mode, size, seconds, files, a.append_mib * 1024**2))
                        if mode == "read":
                            before = tree_digest(dev.mount / "bigfileset", folder / "files.before.json")
                            if len(before) != files:
                                raise RuntimeError("unexpected Filebench file count")
                            actual_bytes = sum(r["bytes"] for r in before)
                            appended = actual_bytes - files * 131072
                            # The original flowop uses lseek+write and stops all
                            # workers together: concurrent appends need not equal
                            # file growth. Keep the original workload, report both,
                            # and reject discrepancies above 1% (1 MiB for smoke).
                            tolerance = max(1024**2, a.append_mib * 1024**2 // 100)
                            if abs(appended - a.append_mib * 1024**2) > tolerance:
                                raise RuntimeError(f"unexpected append volume: {appended}")
                            save(folder / "dataset.json", {"files": len(before), "bytes": actual_bytes,
                                                           "appended_bytes": appended})
                            drop_caches(wait)
                        print(f"  Filebench {mode} " + (f"{a.append_mib} MiB" if mode == "append" else f"{seconds}s"), flush=True)
                        timing = phase(folder, mode, pin + ["setarch", "x86_64", "-R", FILEBENCH, "-f", profile], dev, seconds + 300)
                        result = parse_filebench(folder / f"{mode}.log")
                        if (mode == "read" and result["run_seconds"] != seconds) or result["operations"] <= 0:
                            raise RuntimeError("Filebench did not complete configured duration")
                        if mode == "append" and (result["run_seconds"] >= seconds or
                                result["flowops"].get("appendfile1", {}).get("ops", 0) * size * 1024 < a.append_mib * 1024**2):
                            raise RuntimeError("Filebench did not complete configured append byte budget")
                        if (mode == "read" and not result["reads_s"]) or (mode == "append" and not result["writes_s"]):
                            raise RuntimeError("Filebench did not execute expected data I/O")
                        save(folder / f"{mode}.json", result | timing)
                    after = tree_digest(dev.mount / "bigfileset", folder / "files.after.json")
                    if before != after:
                        raise RuntimeError("Filebench read phase changed file contents")
                    save(folder / "verification.json", {"verified": True, "files": len(after), "method": "SHA256 before/after read"})
                counters(folder / "final.stats")
                for line in (folder / "final.stats").read_text().splitlines():
                    if line.startswith("fast24 "):
                        fields = dict(x.split("=", 1) for x in line.split()[1:])
                        if int(fields["rejected"]) or int(fields["append_hints"]) or int(fields["overwrite_hints"]):
                            raise RuntimeError("unexpected rejected I/O or host file hints")
            finally:
                dev.close()
            save(folder / "case.json", item | {"validated": True})
            print(f"PASS {item['group']} {item['workload']} r{item['repeat']}", flush=True)
        manifest["status"] = "passed"
    except BaseException as exc:
        manifest["status"], manifest["error"] = "failed", str(exc)
        raise
    finally:
        # Writing a *_bytes knob can clear its *_ratio counterpart even when
        # the byte value is zero. Restore the originally active representation.
        for key in ("dirty_writeback_centisecs", "dirty_expire_centisecs"):
            if key in old:
                (Path("/proc/sys/vm") / key).write_text(old[key] + "\n")
        for byte_key, ratio_key in (("dirty_bytes", "dirty_ratio"),
                                    ("dirty_background_bytes", "dirty_background_ratio")):
            if byte_key in old and ratio_key in old:
                key = byte_key if int(old[byte_key]) else ratio_key
                (Path("/proc/sys/vm") / key).write_text(old[key] + "\n")
        if old:
            save(a.out / "vm.restored.json", {key: (Path("/proc/sys/vm") / key).read_text().strip() for key in old})
        save(a.out / "manifest.json", manifest)


if __name__ == "__main__":
    signal.signal(signal.SIGTERM, lambda *_: (_ for _ in ()).throw(KeyboardInterrupt()))
    try:
        main()
    except (RuntimeError, OSError, subprocess.SubprocessError) as exc:
        print("ERROR:", exc, file=sys.stderr)
        sys.exit(1)
